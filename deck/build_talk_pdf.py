def build():
    doc = SimpleDocTemplate(str(OUT), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=1.8 * cm,
                            title="SMT × MemUP: текст к презентации 26.10.2026", author="Ирина Ромадова")
    story = [Paragraph("SMT × MemUP: текст к презентации 26.10.2026", H1),
             Paragraph("Что говорить на каждом слайде и короткие ответы на ожидаемые вопросы. Числа — как на слайдах (состояние "
                       "26.10.2026, 07:30). Источники чисел — deck/SOURCES_AUDIT_RU.md; код — SMT_MemUP_EXPLAINABLE.ipynb.", P)]
    for title, paras, qa in SLIDES:
        block = [Paragraph(title, H2)] + [Paragraph(t, P) for t in paras]
        if qa:
            items = [ListItem([Paragraph(q, Q), Paragraph(a, P)], leftIndent=10) for q, a in qa]
            block.append(ListFlowable(items, bulletType="bullet", start="–", leftIndent=10, bulletFontName="Arial"))
        story.append(KeepTogether(block))
    story += [PageBreak(), Paragraph("Карта: слайд → данные → ноутбук", H2)]
    t = Table([[Paragraph(c, SMALL) for c in row] for row in MAP], colWidths=[2.0 * cm, 9.5 * cm, 5.5 * cm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, "#888888"), ("BACKGROUND", (0, 0), (-1, 0), "#eeeeee"), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(t)
    doc.build(story)
    print("saved", OUT.relative_to(ROOT))


